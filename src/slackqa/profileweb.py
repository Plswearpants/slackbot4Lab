def _page(title: str, body: str) -> web.Response:
    doc = (
        '<!doctype html><html lang="en"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width,initial-scale=1">'
        f"<title>{html.escape(title)}</title><style>{CSS}</style></head>"
        f'<body><div class="wrap">{body}</div></body></html>'
    )
    return web.Response(text=doc, content_type="text/html")


def _paras(text: str) -> str:
    blocks = [b.strip() for b in text.split("\n\n") if b.strip()]
    return "".join(f"<p>{html.escape(b)}</p>" for b in blocks) or (
        '<p class="empty">Not yet written.</p>'
    )


def _badges(p: Profile) -> str:
    out = [f'<span class="tag kindtag">{p.kind}</span>']
    out.append(
        '<span class="tag ok">endorsed</span>'
        if p.endorsed
        else '<span class="tag prov">unreviewed</span>'
    )
    if p.kind == PERSON and not p.active():
        out.append('<span class="tag dormant">dormant</span>')
    return "".join(out)


def render_index(profiles: list[Profile]) -> str:
    n_ok = sum(1 for p in profiles if p.endorsed)
    parts = [
        "<h1>LAIR profiles</h1>",
        f'<p class="sub">{len(profiles)} profiles · {n_ok} endorsed · '
        f"{len(profiles) - n_ok} unreviewed. Generated from the group's Slack "
        "history; the markdown files are the source of truth.</p>",
    ]
    for kind, label in ((INSTRUMENT, "Instruments"), (PERSON, "People")):
        group = sorted(
            (p for p in profiles if p.kind == kind),
            key=lambda x: (x.kind == PERSON and not x.active(), x.name.lower()),
        )
        if not group:
            continue
        parts.append(f'<h2 class="sec">{label} ({len(group)})</h2>')
        for p in group:
            blurb = p.abstract.split("\n\n")[0][:180] if p.abstract else ""
            last = p.last_active() or "—"
            parts.append(
                f'<div class="card"><div class="row">'
                f'<a class="name" href="/profiles/{p.kind}/{_slug(p)}">'
                f"{html.escape(p.name)}</a>{_badges(p)}"
                f'<span style="margin-left:auto;color:#9aa0a8;font-size:.82rem">'
                f"last {html.escape(last)}</span></div>"
                f'<div class="blurb">{html.escape(blurb)}</div></div>'
            )
    return "".join(parts)


def _slug(p: Profile) -> str:
    from slackqa.profiles import slug

    return slug(p.name)


def render_profile(p: Profile) -> str:
    parts = [
        '<div class="crumb"><a href="/profiles">← all profiles</a></div>',
        f"<h1>{html.escape(p.name)}</h1>",
        f'<div class="row" style="margin-bottom:1.4rem">{_badges(p)}</div>',
        '<h2 class="sec">Abstract</h2>',
        f'<div class="abstract">{_paras(p.abstract)}</div>',
    ]

    if p.systems:
        chips = "".join(
            f'<span class="chip">{html.escape(s.strip())}</span>'
            for s in p.systems.split(",")
            if s.strip()
        )
        parts += ['<h2 class="sec">Sample systems</h2>', f'<div class="systems">{chips}</div>']

    parts.append('<h2 class="sec">Timeline</h2>')
    if not p.timeline:
        parts.append('<p class="empty">No entries yet.</p>')
    slug_ = _slug(p)
    base = f"/profiles/{p.kind}/{slug_}"
    for e in p.timeline:
        grain = "month" if e.monthly else "year"
        eid = e.period.replace("-", "")
        marks = []
        if e.endorsed_by:
            marks.append(
                f'<span class="tick">endorsed</span> by {html.escape(e.endorsed_by)}'
            )
        if e.edited_by:
            marks.append(f"edited by {html.escape(e.edited_by)}")
        if not marks:
            marks.append("unreviewed")

        parts.append(
            f'<div class="entry {"" if e.monthly else "year"}">'
            f'<div class="period">{html.escape(e.period)}'
            f'<span class="grain">{grain}</span></div>'
            f"<div>{html.escape(e.text)}"
            f'<div class="prov">{" &middot; ".join(marks)}'
            f"<button onclick=\"document.getElementById('en{eid}')"
            f".classList.toggle('hidden')\">endorse</button>"
            f"<button onclick=\"document.getElementById('ed{eid}')"
            f".classList.toggle('hidden')\">edit</button></div>"

            f'<form id="en{eid}" class="mini hidden" method="post" '
            f'action="{base}/entry/{e.period}/endorse">'
            '<input type="text" name="actor" placeholder="your name" required>'
            '<div class="actions"><button class="primary" type="submit">'
            "Endorse this entry</button></div></form>"

            f'<form id="ed{eid}" class="mini hidden" method="post" '
            f'action="{base}/entry/{e.period}/edit">'
            '<input type="text" name="actor" placeholder="your name" required>'
            f'<textarea name="text">{html.escape(e.text)}</textarea>'
            '<div class="actions"><button class="primary" type="submit">'
            "Save entry</button></div></form>"

            "</div></div>"
        )

    slug_ = _slug(p)
    base = f"/profiles/{p.kind}/{slug_}"
    parts += [
        '<div class="warn"><b>Unauthenticated demo.</b> Anyone who can reach this '
        "page can endorse or edit. Every action is recorded with the name given "
        "below, so put your real one.</div>",
        '<div class="actions">',
        f"<button onclick=\"document.getElementById('endorse').classList.toggle('hidden')\">"
        f"{'Re-endorse' if p.endorsed else 'Endorse'}</button>",
        "<button onclick=\"document.getElementById('edit').classList.toggle('hidden')\">"
        "Edit</button>",
        "</div>",

        f'<form id="endorse" class="panel hidden" method="post" action="{base}/endorse">',
        "<label>Your name</label>",
        '<input type="text" name="actor" placeholder="e.g. Dong Chen" required>',
        '<div class="actions"><button class="primary" type="submit">'
        "Endorse this profile</button></div>",
        "</form>",

        f'<form id="edit" class="panel hidden" method="post" action="{base}/edit">',
        "<label>Your name</label>",
        '<input type="text" name="actor" placeholder="e.g. Dong Chen" required>',
        "<label>Abstract</label>",
        f'<textarea name="abstract">{html.escape(p.abstract)}</textarea>',
        "<label>Sample systems (comma separated)</label>",
        f'<input type="text" name="systems" value="{html.escape(p.systems)}">',
        '<div class="actions"><button class="primary" type="submit">Save</button>'
        "</div>",
        "</form>",
    ]

    meta = []
    if p.source:
        meta.append(
            f'Abstract seeded from <a href="{html.escape(p.source)}">the lab page</a>'
        )
    if p.endorsed_by:
        meta.append(f"Endorsed by {html.escape(p.endorsed_by)}")
    if p.updated:
        meta.append(f"Updated {html.escape(p.updated)}")
    if meta:
        parts.append(f'<div class="meta">{" · ".join(meta)}</div>')
    return "".join(parts)


async def index(request: web.Request) -> web.Response:
    store: Profiles = request.app[PROFILES]
    return _page("LAIR profiles", render_index(store.all()))


async def detail(request: web.Request) -> web.Response:
    store: Profiles = request.app[PROFILES]
    kind = request.match_info["kind"]
    want = request.match_info["slug"]
    for p in store.all(kind if kind in (PERSON, INSTRUMENT) else None):
        if _slug(p) == want:
            return _page(f"{p.name} — LAIR profiles", render_profile(p))
    raise web.HTTPNotFound(text="No such profile")


async def as_json(request: web.Request) -> web.Response:
    store: Profiles = request.app[PROFILES]
    out: list[dict[str, Any]] = []
    for p in store.all():
        out.append(
            {
                "name": p.name, "kind": p.kind, "endorsed": p.endorsed,
                "active": p.active(), "last": p.last_active(),
                "abstract": p.abstract, "systems": p.systems,
                "timeline": [{"period": e.period, "text": e.text} for e in p.timeline],
            }
        )
    return web.json_response(out)


def _find(store: Profiles, kind: str, want: str) -> Profile | None:
    for p in store.all(kind if kind in (PERSON, INSTRUMENT) else None):
        if _slug(p) == want:
            return p
    return None


async def endorse(request: web.Request) -> web.Response:
    store: Profiles = request.app[PROFILES]
    form = await request.post()
    actor = str(form.get("actor", "")).strip()
    if not actor:
        raise web.HTTPBadRequest(text="A name is required to endorse.")

    kind, want = request.match_info["kind"], request.match_info["slug"]
    p = _find(store, kind, want)
    if p is None:
        raise web.HTTPNotFound(text="No such profile")

    from datetime import date

    p.endorsed_by = f"{actor} ({date.today().isoformat()})"
    store.save(p)
    await _audit(request, p, "endorse", actor)
    raise web.HTTPFound(f"/profiles/{p.kind}/{want}")


async def edit(request: web.Request) -> web.Response:
    store: Profiles = request.app[PROFILES]
    form = await request.post()
    actor = str(form.get("actor", "")).strip()
    if not actor:
        raise web.HTTPBadRequest(text="A name is required to edit.")

    kind, want = request.match_info["kind"], request.match_info["slug"]
    p = _find(store, kind, want)
    if p is None:
        raise web.HTTPNotFound(text="No such profile")

    changed = []
    abstract = str(form.get("abstract", "")).strip()
    systems = str(form.get("systems", "")).strip()
    if abstract != p.abstract:
        changed.append("abstract")
        p.abstract = abstract
    if systems != p.systems:
        changed.append("systems")
        p.systems = systems

    if changed:
        store.save(p)
        await _audit(request, p, "edit", actor, ", ".join(changed))
    raise web.HTTPFound(f"/profiles/{p.kind}/{want}")


async def _audit(request: web.Request, p: Profile, action: str, actor: str,
                 detail: str = "") -> None:
    """Record the action if a store is attached. The dashboard runs without one
    in tests, and an unrecorded edit is better than a failed one."""
    store = request.app.get(AUDIT)
    if store is None:
        return
    try:
        await store.record_profile_action(p.name, p.kind, action, actor, detail)
    except Exception:  # pragma: no cover - the edit already succeeded
        pass


async def entry_action(request: web.Request) -> web.Response:
    """Endorse or edit a single timeline entry."""
    from datetime import date

    store: Profiles = request.app[PROFILES]
    form = await request.post()
    actor = str(form.get("actor", "")).strip()
    if not actor:
        raise web.HTTPBadRequest(text="A name is required.")

    kind, want = request.match_info["kind"], request.match_info["slug"]
    period, what = request.match_info["period"], request.match_info["what"]
    p = _find(store, kind, want)
    if p is None:
        raise web.HTTPNotFound(text="No such profile")
    entry = p.entry_for(period)
    if entry is None:
        raise web.HTTPNotFound(text=f"No entry for {period}")

    stamp = f"{actor} ({date.today().isoformat()})"
    if what == "endorse":
        entry.endorsed_by = stamp
        detail = period
    else:
        text = " ".join(str(form.get("text", "")).split())
        if not text:
            raise web.HTTPBadRequest(text="An entry cannot be emptied.")
        if text == entry.text:
            raise web.HTTPFound(f"/profiles/{p.kind}/{want}")
        entry.text = text
        entry.edited_by = stamp
        detail = f"{period}: text"

    store.save(p)
    await _audit(request, p, f"entry-{what}", actor, detail)
    raise web.HTTPFound(f"/profiles/{p.kind}/{want}")


PROFILES = web.AppKey("profiles", Profiles)
AUDIT = web.AppKey("audit_store", object)


def attach(app: web.Application, profiles_dir, store=None) -> None:
    app[PROFILES] = Profiles(profiles_dir)
    if store is not None:
        app[AUDIT] = store
    app.router.add_get("/profiles", index)
    app.router.add_get("/profiles.json", as_json)
    app.router.add_get("/profiles/{kind}/{slug}", detail)
    app.router.add_post("/profiles/{kind}/{slug}/endorse", endorse)
    app.router.add_post("/profiles/{kind}/{slug}/edit", edit)
    app.router.add_post(
        "/profiles/{kind}/{slug}/entry/{period}/{what:endorse|edit}", entry_action
    )
