"""Browsable HTML for entity profiles, served by the same dashboard.

The markdown files stay the source of truth — agents read and write them
directly — and this is a view over them, re-read on every request so a profile
edited by hand or regenerated by a build shows up without a restart.

Rendered semantically rather than as generic markdown: the abstract, the sample
systems and the timeline mean different things and earn different treatment. The
timeline in particular distinguishes monthly entries from yearly ones, because
that difference is the whole point of the rolling resolution — recent months are
detail, older years are summary, and a reader should see which they are looking
at.
"""

